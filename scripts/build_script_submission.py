"""Turn an optimised 720-turn action script into a submittable, dependency-free `submission/main.py`.

Task #9's other half. `scripts/optimise_script.py` produces a `.npz` of raw action arrays for our
seat; this converts them into the environment's own JSON action format and embeds them in a single
file that imports nothing but the standard library.

**All the index-to-name mapping happens here, at build time, not at run time.** Op codes, crop names,
item names and market order slotting are all resolved into literal JSON before embedding, so the
submitted file contains no lookup tables to get wrong and its `agent()` is a dictionary read. That is
deliberate: `CLAUDE.md` records a hand-rolled `main.py` that failed to import and banked exactly the
$3,000 starting money, and the less logic that ships, the less there is to fail in an environment we
cannot debug.

**Two things must be faithful or the replay diverges from what the optimiser measured.**

1. **Market order slot order.** The reference pairs the two players' i-th *orders* and resolves them
   in lockstep, so which order sits in which slot changes the prices both players see. The emitted
   list therefore follows `jax_sim._order_book` exactly -- sells, seeds, products, animals, then one
   slot per HIRE, then one per BUY_LAND -- truncated at `maxMarketOrdersPerTurn`.
2. **One action per unit owned.** The script carries 24 unit slots but the farm owns far fewer. The
   reference ignores a surplus unit action for movement and work, but still counts it in the atomic
   PLANT rule, so a submission that fills all 24 slots can block plants that no real agent could
   block. `CLAUDE.md` records this exact mistake being written up as a simulator bug. The runtime
   therefore truncates `hands` to the number of hands the observation actually reports.

    PYTHONPATH=. python3 -u scripts/build_script_submission.py \
        --script data/opt_scripts/opt_heuristic_seed0.npz
"""

import argparse
import base64
import json
import pathlib
import sys
import zlib

import numpy as np

from kagg.sim.market import ANIMALS, PRODUCTS
from kagg.sim.tiles import CROPS

# Op code -> the reference's own op string. NOOP covers both PASS and any illegal action.
OP_NAMES = [
    "PASS", "NORTH", "SOUTH", "EAST", "WEST",
    "WATER", "HARVEST", "PLANT", "DIG",
    "PICKUP", "DROP", "PLACE", "FEED", "CARE", "COLLECT_FERTILIZER", "FERTILIZE",
    "BUILD_COOP", "BUILD_PASTURE",
]
CROP_NAMES = list(CROPS)
ITEM_NAMES = list(PRODUCTS) + list(ANIMALS)
MAX_ORDERS = 10

# Only these carry arguments. `DROP` deliberately does not: the reference dumps the unit's *entire*
# inventory into the shed and ignores any argument, so emitting one would be misleading.
NEEDS_CROP = {OP_NAMES.index("PLANT")}
NEEDS_ITEM_QTY = {OP_NAMES.index("PICKUP"), OP_NAMES.index("PLACE")}


def unit_action(op, crop, item, qty):
    name = OP_NAMES[int(op)]
    if int(op) in NEEDS_CROP:
        return [name, CROP_NAMES[int(crop) % len(CROP_NAMES)]]
    if int(op) in NEEDS_ITEM_QTY:
        return [name, ITEM_NAMES[int(item) % len(ITEM_NAMES)], max(1, int(qty))]
    return [name]


def market_orders(t, s):
    """One turn's market orders, in `jax_sim._order_book` slot order, capped at `MAX_ORDERS`."""
    orders = []
    for i, name in enumerate(PRODUCTS):
        n = int(s["sell"][t, i])
        if n > 0:
            orders.append(["SELL", name, n])
    for c, name in enumerate(CROP_NAMES):
        n = int(s["buy_seed"][t, c])
        if n > 0:
            orders.append(["BUY_SEED", name, n])
    for i, name in enumerate(PRODUCTS):
        n = int(s["buy_product"][t, i])
        if n > 0:
            orders.append(["BUY_PRODUCT", name, n])
    for a, name in enumerate(ANIMALS):
        n = int(s["buy_animal"][t, a])
        if n > 0:
            orders.append(["BUY_ANIMAL", name, n])
    # HIRE and BUY_LAND are atomic per order *slot*, not per turn, so a count of n takes n slots.
    # Pinned by `tests/test_multiple_hires_per_turn.py`.
    orders += [["HIRE"]] * int(s["hire"][t])
    orders += [["BUY_LAND"]] * int(s["buy_land"][t])
    return orders[:MAX_ORDERS]


def build_plan(script):
    """`[[farmer, hands, market], ...]` for every turn, with all names already resolved."""
    ops = script["unit_op"]
    T, U = ops.shape
    plan = []
    for t in range(T):
        units = [unit_action(ops[t, u], script["unit_crop"][t, u],
                             script["unit_item"][t, u], script["unit_qty"][t, u])
                 for u in range(U)]
        plan.append([units[0], units[1:], market_orders(t, script)])
    return plan


RUNTIME = '''\
# Generated by scripts/build_script_submission.py -- do not edit.
# Edit the source script (.npz) and rebuild, so the submitted file cannot drift from the tested one.
"""An open-loop 720-turn action script, replayed turn by turn.

Not a policy. Top finishers in this competition submit a fixed sequence -- verified by diffing the
current #1's replays across five episodes in both seats against five opponents, where their per-turn
actions are byte-identical -- and this is that artifact for our own optimised script.

Every op code, crop name, item name and market order slot was resolved at build time. The only
run-time logic is the one thing that genuinely cannot be precomputed: how many hands the farm owns
this turn. The reference still counts a surplus unit action in its atomic PLANT rule, so submitting
more unit actions than units owned can block plants a real agent could not block.
"""

import base64
import json
import zlib

_BLOB = "{blob}"
_PLAN = None
_PASS = {{"farmer": ["PASS"], "hands": [], "market": []}}


def _plan():
    global _PLAN
    if _PLAN is None:
        _PLAN = json.loads(zlib.decompress(base64.b64decode(_BLOB)).decode())
    return _PLAN


def _get(obs, key, default=None):
    if isinstance(obs, dict):
        return obs.get(key, default)
    return getattr(obs, key, default)


def agent(obs, config=None):
    plan = _plan()
    step = int(_get(obs, "step", 0) or 0)
    if step >= len(plan):
        return dict(_PASS)
    farmer, hands, market = plan[step]

    # Truncate to the hands the farm actually owns. `farms` is absent only if the observation shape
    # is not what we expect, in which case sending the farmer action alone is the safe read.
    n_hands = 0
    farms = _get(obs, "farms")
    if farms:
        me = int(_get(obs, "player", 0) or 0)
        if me < len(farms):
            n_hands = len(farms[me].get("hands", []) or [])
    return {{"farmer": farmer, "hands": hands[:n_hands], "market": market}}
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--script", default="data/opt_scripts/opt_heuristic_seed0.npz")
    ap.add_argument("--out", default="submission/main.py")
    ap.add_argument("--verify", action="store_true",
                    help="play the built file against `starter` in the arena before accepting it")
    a = ap.parse_args()

    blob = np.load(a.script)
    fields = ("unit_op", "unit_crop", "unit_item", "unit_qty",
              "sell", "buy_seed", "buy_product", "buy_animal", "hire", "buy_land")
    script = {f: np.asarray(blob[f]) for f in fields}
    # A checkpoint holds our seat only; a raw recording holds both. Take seat 0 if the seat axis
    # survived, so the same builder works on either.
    if script["unit_op"].ndim == 3:
        script = {f: v[:, 0] for f, v in script.items()}

    plan = build_plan(script)
    packed = base64.b64encode(zlib.compress(json.dumps(plan, separators=(",", ":")).encode(), 9))
    out = pathlib.Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(RUNTIME.format(blob=packed.decode()))

    iters = int(blob["iter"]) if "iter" in blob else -1
    print(f"source {a.script}  (iteration {iters}, "
          f"{'wins %s' % blob['wins'] if 'wins' in blob else 'no score recorded'})")
    print(f"{len(plan)} turns, {script['unit_op'].shape[1]} unit slots")
    print(f"hire orders {int(script['hire'].sum())}, buy_land {int(script['buy_land'].sum())}, "
          f"animals {int(script['buy_animal'].sum())}")
    print(f"wrote {out}  ({out.stat().st_size / 1e3:.0f} kB, "
          f"{len(out.read_text().splitlines())} lines)")

    if a.verify:
        from kagg.arena import run_arena
        report = run_arena(str(out), "starter", seeds=[600, 601, 602, 603], workers=4)
        print(report)
        # A module that fails to import banks exactly the starting money, so at-or-below the start
        # is a build failure rather than a weak agent.
        if not (report.mean_money[0] > 3000.0):
            print("BUILD FAILED: submission does not beat its own starting money", file=sys.stderr)
            return 1
        print("submission verified against starter")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
