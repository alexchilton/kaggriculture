"""A/B a SELL policy against a recorded season, with the farm held fixed.

Every observational test of "does he sell at good prices" is circular: selling moves the price, so a
seller who trades often looks like a seller who trades badly. The only non-circular test is to hold
everything else constant and change the rule.

That is possible here because the farm and the market separate cleanly -- two of mtmr_s1's seasons
share a byte-identical 719-turn farm and identical sell TOTALS per product, differing only in which
hour each sale goes out. So:

    farm ops      replayed verbatim from the recording
    non-SELL market orders  replayed verbatim (feed, seed, hires, animals -- the farm depends on them)
    SELL orders   generated by the policy under test
    opponent      replayed verbatim
    seed, config  the recording's own

`kagg/analysis/fills.py` wraps `_commit_unit`, so units and revenue are what actually traded.

    python -u scripts/market_counterfactual.py 107041112 107399673

The `recorded` arm re-emits the recording's own SELLs and must reproduce it; it is the harness's
own check, and a run where it does not match is a broken harness, not a finding.
"""
import collections, json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
DIRS = ["data/replays_2026-09-07", "data/replays_2026-09-08", "data/replays_2026-09-09",
        "data/replays_2026-09-11", "data/replays_hayashi", "data/replays_spa_sub"]
SLOTS = 10
#: WHEAT is NOT here, deliberately. It is the herd's feed: the farm's replayed PICKUP/FEED ops draw
#: it from the same shed, so a policy free to sell it starves the animals, they escape, and the
#: season produces no milk, wool or eggs to sell later. Measured: `dump_all` moved 155 units against
#: the recording's 1,617 -- it was not a bad timing rule, it had eaten the farm. The recording's own
#: WHEAT sells are replayed verbatim instead.
SELLABLE = ("CARROT", "TOMATO", "STRAWBERRY", "MELON", "EGG", "MILK", "WOOL", "FERTILIZER")


def find(ep):
    return next((ROOT / d / f"{ep}.json" for d in DIRS if (ROOT / d / f"{ep}.json").exists()), None)


# ---- policies: (obs, turn, recorded_sells, state) -> list of SELL orders -------------------------

def recorded(obs, t, rec, st):
    return rec


def dump_all(obs, t, rec, st):
    """Offer the whole shed of everything, every turn. The upper bound on impatience."""
    shed = (obs.get("private") or {}).get("shed") or {}
    return [["SELL", p, int(shed.get(p, 0))] for p in SELLABLE if int(shed.get(p, 0)) > 0][:SLOTS]


def slice_k(k):
    """Release at most k units of each product per turn, oldest-first by book value."""
    def f(obs, t, rec, st):
        shed = (obs.get("private") or {}).get("shed") or {}
        px = (obs.get("market") or {}).get("prices") or {}
        have = [(p, int(shed.get(p, 0))) for p in SELLABLE if int(shed.get(p, 0)) > 0]
        have.sort(key=lambda pq: -px.get(pq[0], 0) * min(pq[1], k))
        return [["SELL", p, min(q, k)] for p, q in have][:SLOTS]
    f.__name__ = f"slice{k}"
    return f


def above_mean(win, alpha):
    """Hold unless the quote beats `alpha` x its own mean over the last `win` turns."""
    def f(obs, t, rec, st):
        shed = (obs.get("private") or {}).get("shed") or {}
        px = (obs.get("market") or {}).get("prices") or {}
        hist = st.setdefault("hist", collections.defaultdict(list))
        out = []
        for p in SELLABLE:
            now = px.get(p)
            if now is not None:
                hist[p].append(now)
                del hist[p][:-win]
            q = int(shed.get(p, 0))
            if q <= 0 or now is None or len(hist[p]) < win:
                continue
            if now >= alpha * (sum(hist[p]) / len(hist[p])):
                out.append(["SELL", p, q])
        # never strand stock at the bell
        if t >= 24 * 29:
            out = [["SELL", p, int(shed.get(p, 0))] for p in SELLABLE if int(shed.get(p, 0)) > 0]
        return out[:SLOTS]
    f.__name__ = f"above_mean{win}x{alpha}"
    return f


# `above_mean(win, alpha)` is the arm that survived the first pass: hold unless the quote is at or
# above `alpha` x its own mean over the last `win` turns. On mtmr_s1's seat of 107041112 it sold 432
# FEWER units for more money -- $116.6/unit against the recording's $82.4 -- and banked +4,984. The
# sweep below is on the window and the bar, because one episode on one seat is not a result.


def uncapped(f):
    """Mark an arm as free to exceed the recording's per-product totals.

    The capped sweep could only ever sell the same or FEWER units, so "fewer units banked less" was
    forced by the design and says nothing about whether moving MORE would win. These arms remove
    that ceiling; feed wheat stays protected either way.
    """
    f.uncapped = True
    return f


@uncapped
def fert_strike(obs, t, rec, st):
    """Sell FERTILIZER as early and as hard as possible; everything else as recorded.

    Fertilizer is carried by no shop and excluded from `TOWN_CENTER_PRODUCTS`, so its book never
    drains: whatever is sold into it lowers the price for the rest of the season, for BOTH farms.
    That makes an early dump a denial move whose value is in the opponent's column, not ours -- so
    it is scored on margin.
    """
    shed = (obs.get("private") or {}).get("shed") or {}
    out = [o for o in rec if o[1] != "FERTILIZER"]
    n = int(shed.get("FERTILIZER", 0))
    if n > 0:
        out.insert(0, ["SELL", "FERTILIZER", n])
    return out


@uncapped
def sell_when_book_is_thin(obs, t, rec, st):
    """Sell into the books the TOWN is draining faster than they are being filled.

    **What the agent can actually see.** The opponent's shed is NOT observable -- `farms[opp]` has
    only farmer/hands/hires_today/money/tiles/unlocked_quadrants, and holdings live in `private`,
    which is per seat. So an arm that targets what they hold is unimplementable, however clear the
    asymmetry looks in a replay file.

    `market.inventory` IS shared, and it carries the same information indirectly: it rises when
    either farm sells and falls when the town consumes. Measured on 107642213 at step 100 --
    CARROT/MELON/MILK/STRAWBERRY/TOMATO/EGG all at 9,995 (the town is keeping up), WHEAT 9,978 and
    WOOL 9,981 (draining faster than anyone fills), FERTILIZER 10,029 (never drains, both sides
    pushing into it).

    Below `MARKET_I0` the book is thin and the price is above base; above it the book is glutted.
    So: sell what is below baseline, hold what is above. No hour, no threshold on price, no guess
    about the opponent -- just the level the environment publishes.
    """
    import kaggle_environments.envs.kaggriculture.kaggriculture as _K
    shed = (obs.get("private") or {}).get("shed") or {}
    inv = (obs.get("market") or {}).get("inventory") or {}
    base = getattr(_K, "MARKET_I0", 10000)
    out = []
    for prod in SELLABLE:
        q = int(shed.get(prod, 0))
        if q > 0 and inv.get(prod, base) < base:
            out.append(["SELL", prod, q])
    hit = {o[1] for o in out}
    return out + [o for o in rec if o[1] not in hit]


@uncapped
def passthrough(obs, t, rec, st):
    """Re-emit the recording's own SELLs through the arm path. A null: must match `recorded`.

    `recorded` returns the turn verbatim and never exercises the rebuild, so it cannot detect a
    harness that mangles the turn. This one goes through the same split/reassemble every real arm
    uses, with an identity rule. Any gap between this row and `recorded` is the harness, not a
    finding -- and three sweeps were reported before this check existed.
    """
    return rec

def after_day(day, inner):
    """Replay the recording's own sells until `day`, then hand over to `inner`.

    His two identical-farm seasons agree on the market for the first 313-433 turns and only then
    diverge, so the first twelve days are part of the tape and are not the rule's to change. Running
    a candidate over the whole season replaces a tuned opening with an untested one and measures
    both at once -- which is what the first sweep did, and it lost on 9 of 10 seats.
    """
    def f(obs, t, rec, st):
        return rec if t < 24 * day else inner(obs, t, rec, st)
    f.__name__ = f"d{day}+{inner.__name__}"
    return f

ARMS = [recorded, passthrough]


def play(ep, seat_under_test, policy, caps=None):
    rep = json.loads(find(ep).read_text())
    teams, seed = rep["info"]["TeamNames"], rep["info"]["seed"]
    cfg = dict(rep.get("configuration") or {})
    cfg.pop("seed", None)
    acts = []
    for step in rep["steps"][1:]:
        row = []
        for s in step:
            a = (s or {}).get("action") or {}
            row.append({"farmer": a.get("farmer", ["PASS"]) or ["PASS"],
                        "hands": list(a.get("hands") or []),
                        "market": list(a.get("market") or [])})
        acts.append(row)
    idle = {"farmer": ["PASS"], "hands": [], "market": []}

    def agent(seat):
        st, box = {}, {"t": 0}

        def f(obs):
            t = box["t"]
            box["t"] += 1
            if t >= len(acts) or seat >= len(acts[t]):
                return idle
            a = acts[t][seat]
            if seat != seat_under_test:
                return a
            if policy is recorded:
                # Verbatim, so the baseline reproduces the recording exactly. Rebuilding even the
                # identical orders reorders them, and `_process_market` settles in SLOT order --
                # a SELL below a BUY funds nothing, so the same orders in a different order are a
                # different turn. Measured: rebuilt-but-identical lost binghua 102 units of fill.
                return a
            keep = [o for o in a["market"]
                    if not (o and o[0] == "SELL" and o[1] in SELLABLE)]
            rec = [o for o in a["market"] if o and o[0] == "SELL" and o[1] in SELLABLE]
            sells = policy(obs, t, rec, st)
            # **Same goods, same totals -- only the hour is the arm's to choose.** Without this an
            # arm that simply sells MORE scores higher and the comparison is about quantity, not
            # timing. The cap is the baseline run's own filled units per product, so every arm is
            # allowed exactly what the recording actually traded. This is the constraint his own
            # seasons obey: identical per-product totals to the unit, differing only in which hour
            # each slice goes out.
            if caps is not None and not getattr(policy, "uncapped", False):
                out = []
                for o in sells:
                    room = caps.get(o[1], 0) - st.setdefault("sold", collections.Counter())[o[1]]
                    n = min(int(o[2]), max(0, room))
                    if n > 0:
                        out.append(["SELL", o[1], n])
                        st["sold"][o[1]] += n
                sells = out
            # **Sells first in ORDER, last in PRIORITY.** Two separate things, and conflating them
            # voided three sweeps.
            #
            # Order: proceeds settle before anything below them can spend, so sells go at the top --
            # that is how every recorded agent writes its turn.
            #
            # Priority: there are only ORDER_SLOTS (10) of them. `(sells + keep)[:SLOTS]` put eight
            # products' sells at the front and pushed the farm's own BUY_PRODUCT and HIRE off the
            # end, so the herd went unfed and the crew unhired. Every arm then traded FEWER units
            # than the recording -- even `dump_all`, which offered the whole shed every turn and
            # moved 836 units against 1,535 -- and that reads exactly like a bad rule.
            #
            # The farm's orders are not the arm's to drop. They are reserved; sells take what is
            # left.
            room = max(0, SLOTS - len(keep))
            return {"farmer": a["farmer"], "hands": a["hands"],
                    "market": sells[:room] + keep}
        return f

    from kaggle_environments import make
    from kagg.analysis.fills import record_fills
    env = make("kaggriculture", configuration=dict(cfg, seed=seed), debug=True)
    env.reset(2)
    with record_fills(env) as fills:
        env.run([agent(0), agent(1)])
    u = r = 0
    per = collections.Counter()
    for e in fills.events:
        if e["seat"] == seat_under_test and e["op"] == "SELL":
            u += 1
            r += e["price"]
            per[e["item"]] += 1
    farms = env.state[0].observation["farms"]
    bank = farms[seat_under_test]["money"]
    opp = farms[1 - seat_under_test]["money"]
    return teams[seat_under_test], u, r, bank, per, opp


def main():
    for ep in sys.argv[1:]:
        rep = json.loads(find(int(ep)).read_text())
        for seat in range(len(rep["info"]["TeamNames"])):
            print(f"\n=== episode {ep} seat {seat} "
                  f"({rep['info']['TeamNames'][seat]}) ===", flush=True)
            # **Margin, not bank.** The ladder scores match outcome, so a move that costs us $1 and
            # costs the opponent $5 is a win and reads as a loss on a bank-only column. Every arm
            # before this one was scored on its own bank alone.
            print(f"{'arm':22}{'units':>8}{'$/unit':>9}{'bank':>11}{'opponent':>11}"
                  f"{'MARGIN':>11}{'vs rec':>10}", flush=True)
            base, caps = None, None
            for arm in ARMS:
                try:
                    team, u, r, bank, per, opp = play(int(ep), seat, arm, caps)
                except Exception as e:
                    print(f"{arm.__name__:22} FAILED {type(e).__name__} {e}", flush=True)
                    continue
                if base is None:
                    base, caps = bank - opp, dict(per)
                print(f"{arm.__name__:22}{u:>8,}{(r/u if u else 0):>9.1f}{bank:>11,.0f}"
                      f"{opp:>11,.0f}{bank-opp:>11,.0f}"
                      f"{'' if arm is recorded else f'{bank-opp-base:>+10,.0f}'}", flush=True)


if __name__ == "__main__":
    main()
