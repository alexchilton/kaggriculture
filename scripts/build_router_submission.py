"""Bundle the routed schedule agent into one dependency-free `submission/main.py`.

`scripts/build_submission.py` copies a single self-contained agent file verbatim, which is the safest
possible build and is why it exists -- CLAUDE.md records a hand-rolled `main.py` that failed to import
and banked exactly the $3,000 starting money. This agent cannot use it: it is four files
(`routines`, `router`, `schedule_agent`, plus a schedule) and one of them imports numpy.

So rather than splicing text -- the thing that broke last time -- this embeds each module's source
**verbatim as a string** and installs it under its real dotted name in `sys.modules` before the next
one is executed. `from . import routines as R` then resolves exactly as it does in the repo, because it
is the same import machinery reading the same names. No import is rewritten and no source is edited,
so the submitted code is byte-identical to the code the ladder measured.

The schedule is embedded with the four REPLAY-ONLY fields stripped -- `plant_tiles`, `build_tiles`,
`land_turns`, `orders` -- because that is precisely the configuration `scripts/agent_ladder.py` scores.
Shipping the full replay row would submit an agent that was never measured.

`verify` replays the built file through the environment on explicit seeds and refuses to ship anything
at or below the starting bank, since that is the signature of a module that did not import.

Run: python -u scripts/build_router_submission.py
"""

import json
import pathlib
import sys

sys.path.insert(0, ".")

ROOT = pathlib.Path(".")
TARGET = pathlib.Path("submission/main.py")
SCHEDULE = ROOT / "data/seed_scripts/new_leader/schedule.json"
#: Every module the bundle must carry, in import order, as dotted names. `kagg.economics.production`
#: is NOT optional and NOT obvious: `routines.py:603` calls `_crops_fertilizer_helps()` at module scope
#: and that function imports it. A first submission shipped without it and Kaggle logged
#: `ModuleNotFoundError: No module named 'kagg.economics'` -- the whole episode errored on import.
MODULES = ("kagg.economics.production", "kagg.search.routines", "kagg.search.router",
           "kagg.search.schedule_agent")

#: The four fields only a replay can supply. Stripped so the submitted agent is the one that was
#: measured: counts per day, and not one tile coordinate.
TAPE_ONLY = ("plant_tiles", "build_tiles", "land_turns", "orders")

RUNTIME = '''
import json as _json
import sys as _sys
import types as _types

def _package(dotted):
    """Create (once) an empty package module for `dotted` and every parent, and link them up."""
    if dotted in _sys.modules:
        return _sys.modules[dotted]
    mod = _types.ModuleType(dotted)
    mod.__path__ = []
    _sys.modules[dotted] = mod
    if "." in dotted:
        parent, leaf = dotted.rsplit(".", 1)
        setattr(_package(parent), leaf, mod)
    return mod


def _install(dotted, src):
    """Execute one module's verbatim source under its real dotted name.

    Registering in `sys.modules` BEFORE the next module runs is what makes both `from . import
    routines` and `from kagg.economics import production` resolve: the import system finds the
    already-built module instead of looking for a file that is not shipped.
    """
    pkg, leaf = dotted.rsplit(".", 1)
    mod = _types.ModuleType(dotted)
    mod.__package__ = pkg
    _sys.modules[dotted] = mod
    setattr(_package(pkg), leaf, mod)
    exec(compile(src, dotted.replace(".", "/") + ".py", "exec"), mod.__dict__)
    return mod


for _name in _MODULE_ORDER:
    _install(_name, _SOURCES[_name])

_SA = _sys.modules["kagg.search.schedule_agent"]
_SCHEDULE = {int(k): v for k, v in _json.loads(_SCHEDULE_JSON).items()}
_STATE = {"agent": None, "step": -1}


def agent(obs, config=None):
    """One episode per process is not guaranteed, so rebuild whenever the clock goes backwards."""
    step = int(obs.get("step", 0) or 0)
    if _STATE["agent"] is None or step <= _STATE["step"]:
        _STATE["agent"] = _SA.make_agent(_SCHEDULE, int(obs.get("player", 0) or 0), router=True)
    _STATE["step"] = step
    return _STATE["agent"](obs, config)
'''


def build():
    sources = {}
    for name in MODULES:
        sources[name] = (ROOT / (name.replace(".", "/") + ".py")).read_text()
    sched = {k: {kk: vv for kk, vv in row.items() if kk not in TAPE_ONLY}
             for k, row in json.loads(SCHEDULE.read_text()).items()}

    out = ["# Generated by scripts/build_router_submission.py -- do not edit.",
           "# Every module below is the repo source verbatim; edit the source and rebuild.",
           "_MODULE_ORDER = %r" % (MODULES,),
           "_SOURCES = {}"]
    for name in MODULES:
        out.append("_SOURCES[%r] = %r" % (name, sources[name]))
    out.append("_SCHEDULE_JSON = %r" % json.dumps(sched, separators=(",", ":")))
    out.append(RUNTIME)

    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text("\n".join(out))
    return TARGET


def verify_isolated(seed=11):
    """Load the built file the way KAGGLE loads it, from a directory where the repo does not exist.

    **This is the gate that matters, and its absence cost a submission.** The in-process `verify`
    below is not a substitute and cannot be: it runs after `import agent_ladder` has already pulled
    the real `kagg` package into `sys.modules`, so a module the bundle forgot to ship is satisfied
    from the repo and the check passes. Submission 55304259 passed it and then errored on Kaggle with
    `ModuleNotFoundError: No module named 'kagg.economics'` -- CLAUDE.md's "a gate only tests what it
    cannot reach" for the fourth time in this project.

    So: a fresh interpreter, `cwd` in a temp directory, nothing of ours on `sys.path`, and
    `kaggle_environments.make(...).run(...)` doing the loading. If the file cannot stand alone, this
    fails exactly as the competition fails.
    """
    import subprocess
    import tempfile

    src = TARGET.resolve()
    probe = """
import json, sys
from kaggle_environments import make
env = make("kaggriculture", configuration={"seed": %d, "weedSpawnChance": 0.005}, debug=True)
env.run([%r, %r])
bad = []
for i, s in enumerate(env.state):
    if s.status not in ("DONE", "ACTIVE", "INACTIVE"):
        bad.append((i, s.status))
print(json.dumps({"statuses": [s.status for s in env.state],
                  "banks": [float(s.observation["farms"][i]["money"])
                            for i, s in enumerate(env.state)],
                  "bad": bad}))
""" % (seed, str(src), str(src))
    with tempfile.TemporaryDirectory() as tmp:
        script = pathlib.Path(tmp) / "probe.py"
        script.write_text(probe)
        r = subprocess.run([sys.executable, "-u", str(script)], cwd=tmp,
                           capture_output=True, text=True, timeout=1800)
    tail = [ln for ln in r.stdout.splitlines() if ln.startswith("{")]
    if r.returncode != 0 or not tail:
        print(r.stdout[-3000:])
        print(r.stderr[-3000:])
        raise SystemExit("REFUSING TO SHIP: the built file does not run in isolation")
    out = json.loads(tail[-1])
    banks = "  ".join(f"${b:,.0f}" for b in out["banks"])
    print(f"  isolated self-play  statuses {out['statuses']}  banks {banks}")
    if out["bad"] or any(b <= 3000 for b in out["banks"]):
        print(r.stderr[-3000:])
        raise SystemExit(f"REFUSING TO SHIP: {out}")
    return out


def verify(seeds=(11, 22, 33)):
    """Play the BUILT file -- not the repo -- against the tape's opponent on explicit seeds.

    Explicit seeds because `env.reset()` draws a fresh one on every call and one identical tape has
    banked $48,144 and $59,199 on different draws. An unseeded figure here would be no measurement.
    """
    sys.path.insert(0, "scripts")
    sys.path.insert(0, "submission")
    import importlib
    import agent_ladder as L

    main = importlib.import_module("main")
    _mine, theirs = L.tape_plans()
    banks = []
    for seed in seeds:
        env = L._env(seed, 0.005)
        for t in range(719):
            obs = env.state[0].observation
            a = main.agent(obs)
            n0 = len(obs["farms"][0].get("hands") or [])
            n1 = len(obs["farms"][1].get("hands") or [])
            f1, h1, m1 = theirs[t] if t < len(theirs) else (["PASS"], [], [])
            env.step([{"farmer": a["farmer"], "hands": list(a["hands"])[:n0], "market": a["market"]},
                      {"farmer": f1, "hands": list(h1)[:n1], "market": m1}])
            if env.state[0].status == "DONE":
                break
        bank = float(env.state[0].observation["farms"][0]["money"])
        print(f"  seed {seed:>4}   ${bank:>10,.0f}")
        banks.append(bank)
    return banks


def main():
    path = build()
    print(f"built {path}  ({path.stat().st_size:,} bytes)\n")
    # Isolation FIRST. A file that cannot import alone is not worth scoring.
    verify_isolated()
    banks = verify()
    worst = min(banks)
    print(f"\n  mean ${sum(banks) / len(banks):,.0f}   worst ${worst:,.0f}")
    if worst <= 3000:
        raise SystemExit("REFUSING TO SHIP: a bank at or below the $3,000 start means it did not run")
    print("  OK -- the built file runs and farms")


if __name__ == "__main__":
    main()
