"""One row per (game, day) for ONE player: what the board looked like, and which block they played.

This is the dataset behind Alex's question, 2026-08-20: "what is the classification criteria that
returns us a days of tape".

**The unit is the DAY, not the turn.** That is the whole point. `build_bc_rows.py` emits 720 rows a
game -- board snapshot at hour h -> action at hour h -- and the student it trains has to re-derive
the day's plan 24 times from a state that does not contain it. These players decide once, at dawn,
so the row is (features at h0) -> (which of this player's blocks). 30 rows a game instead of 720,
and the label is an id rather than a 24-turn sequence to regenerate.

**Per player, because a block library is per player.** Blocks are hashes of one person's actions;
they do not transfer. Kawashigi has 228 seasons in this repo, which is the sample to use.

**Animal ops are stripped from the label.** Measured 2026-08-20: doing so changes almost nothing
(Kawashigi d8 3.2 -> 3.2 blocks per group, tetsuya identical at every day), so this is not the lever
that makes days matchable -- but the herd IS generated by a known rule from the shop draw, so
storing it in the label is pointless either way.

    python -u scripts/build_day_rows.py --player カワシギ --out data/day_rows_kawa.json \\
        --dirs data/seed_scripts/kawashigi data/seed_scripts/downloads_2026-08-14to16
"""

import argparse
import collections
import glob
import hashlib
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from scripts.count_day_blocks import canonical                          # noqa: E402
from scripts.player_self_consistency import (                           # noqa: E402
    SHOP_BUYS, ANIMAL_PRODUCTS_ALL, plant_only, species_only, shops_of)

TURNS_PER_DAY = 24
CROPS = ("WHEAT", "CARROT", "TOMATO", "STRAWBERRY", "MELON")
PRODUCTS = ("WHEAT", "CARROT", "TOMATO", "STRAWBERRY", "MELON", "MILK", "WOOL", "EGG",
            "FERTILIZER")
ANIMALS = ("GOOSE", "COW", "SHEEP")
ANIMAL_OF = {"EGG": "GOOSE", "MILK": "COW", "WOOL": "SHEEP"}


def tile_counts(farm):
    """What is standing on this farm: crops in the ground, animals, pens, weeds, free soil."""
    out = collections.Counter()
    for row in (farm.get("tiles") or []):
        for t in row:
            if not isinstance(t, dict):
                # Locked quadrants and empty cells come through as strings or None.
                out["LOCKED" if t == "LOCKED" else "EMPTY"] += 1
                continue
            kind = str(t.get("kind"))
            out["kind_%s" % kind] += 1
            crop = t.get("crop")
            if crop:
                out["crop_%s" % crop] += 1
            animal = t.get("animal")
            if animal:
                out["animal_%s" % animal] += 1
            if t.get("watered_today"):
                out["watered"] += 1
            unwatered = t.get("consecutive_unwatered")
            if isinstance(unwatered, int) and unwatered >= 1:
                out["thirsty"] += 1
    return out


def features(obs, seat):
    """Everything a real agent could read at h0. Named, so the tree's rules stay legible."""
    farms = obs.get("farms") or []
    me = farms[seat] if seat < len(farms) else {}
    opp = farms[1 - seat] if (1 - seat) < len(farms) else {}
    private = obs.get("private") or {}
    market = obs.get("market") or {}
    inv = market.get("inventory") or {}

    shops = shops_of(obs)
    f = {"day": int(obs.get("day", 0) or 0)}

    # --- the shop draw, in the three forms that matter ---
    animal_slots = plant_slots = 0
    demand = collections.Counter()
    for s in shops:
        for p in SHOP_BUYS.get(s, ()):
            demand[p] += 1
            if p in ANIMAL_PRODUCTS_ALL:
                animal_slots += 1
            else:
                plant_slots += 1
    f["shop_n"] = len(shops)
    f["shop_animal_slots"] = animal_slots
    f["shop_plant_slots"] = plant_slots
    for p in PRODUCTS:
        f["shop_demand_%s" % p] = demand.get(p, 0)
    for product, animal in ANIMAL_OF.items():
        f["shop_wants_%s" % animal] = demand.get(product, 0)

    # --- our own farm ---
    f["my_money"] = float(me.get("money", 0) or 0)
    f["my_hands"] = len(me.get("hands") or [])
    f["my_quadrants"] = len(me.get("unlocked_quadrants") or [])
    mine = tile_counts(me)
    for c in CROPS:
        f["my_crop_%s" % c] = mine.get("crop_%s" % c, 0)
    for a in ANIMALS:
        f["my_animal_%s" % a] = mine.get("animal_%s" % a, 0)
    f["my_thirsty"] = mine.get("thirsty", 0)
    f["my_weeds"] = mine.get("kind_WEED", 0)
    f["my_empty"] = mine.get("kind_EMPTY", 0) + mine.get("EMPTY", 0)

    # --- private: seeds and shed. Only OUR seat has these. ---
    seeds = private.get("seeds") or {}
    shed = private.get("shed") or {}
    for c in CROPS:
        f["my_seed_%s" % c] = int(seeds.get(c, 0) or 0)
    for p in PRODUCTS:
        f["my_shed_%s" % p] = int(shed.get(p, 0) or 0)

    # --- the opponent, as VISIBLE. Melon is the one Alex called decisive at d3. ---
    f["opp_money"] = float(opp.get("money", 0) or 0)
    f["opp_hands"] = len(opp.get("hands") or [])
    f["opp_quadrants"] = len(opp.get("unlocked_quadrants") or [])
    theirs = tile_counts(opp)
    for c in CROPS:
        f["opp_crop_%s" % c] = theirs.get("crop_%s" % c, 0)
    for a in ANIMALS:
        f["opp_animal_%s" % a] = theirs.get("animal_%s" % a, 0)

    # --- the market. Inventory is what sets price, so it is the causal quantity. ---
    for p in PRODUCTS:
        f["mkt_inv_%s" % p] = int(inv.get(p, 0) or 0)
    return f


def read(path, player, days):
    rep = json.loads(pathlib.Path(path).read_text())
    if not isinstance(rep, dict) or not rep.get("steps"):
        return []
    info = rep.get("info")
    names = info.get("TeamNames") if isinstance(info, dict) else None
    if not names:
        return []
    seats = [i for i, n in enumerate(names) if n == player]
    if not seats:
        return []

    rows = []
    for seat in seats:
        turns = collections.defaultdict(list)
        feats = {}
        for step in rep["steps"]:
            if seat >= len(step):
                continue
            cell = step[seat]
            obs = cell.get("observation") or {}
            day, hour = int(obs.get("day", 0) or 0), int(obs.get("hour", 0) or 0)
            if day >= days:
                continue
            act = cell.get("action")
            if act is None:
                continue
            turns[day].append((hour, canonical(plant_only(act)), canonical(act),
                               canonical(species_only(act))))
            if hour == 0:
                try:
                    feats[day] = features(obs, seat)
                except KeyError:
                    return []                      # no shops field: not a usable replay
        for day, t in turns.items():
            if len(t) != TURNS_PER_DAY or day not in feats:
                continue
            t = sorted(t)
            digest = lambda parts: hashlib.md5(                           # noqa: E731
                "|".join(parts).encode()).hexdigest()[:10]
            rows.append({"game": pathlib.Path(path).stem, "seat": seat, "day": day,
                         # `block` keeps the historical name and stays the default label.
                         "block": digest([p for _h, p, _f, _s in t]),
                         "block_full": digest([f for _h, _p, f, _s in t]),
                         "block_species": digest([s for _h, _p, _f, s in t]),
                         "x": feats[day]})
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--player", required=True)
    ap.add_argument("--dirs", nargs="+", required=True)
    ap.add_argument("--days", type=int, default=30)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    paths = []
    for d in args.dirs:
        paths += sorted(glob.glob(d.rstrip("/") + "/*.json"))
    rows = []
    for p in paths:
        rows += read(p, args.player, args.days)

    games = {(r["game"], r["seat"]) for r in rows}
    print("player %s: %d day-rows from %d game-seats" % (args.player, len(rows), len(games)))
    per_day = collections.defaultdict(collections.Counter)
    for r in rows:
        per_day[r["day"]][r["block"]] += 1
    print("\n%4s %8s %10s %8s   how many blocks cover 90%%" % ("day", "rows", "distinct", "top"))
    for day in sorted(per_day):
        c = per_day[day]
        n = sum(c.values())
        run = 0
        need = 0
        for _b, v in c.most_common():
            run += v
            need += 1
            if run >= 0.9 * n:
                break
        print("%4d %8d %10d %7.1f%% %8d" % (day, n, len(c), 100.0 * c.most_common(1)[0][1] / n, need))

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(rows))
    print("\nwrote %s  (%d rows, %d features)"
          % (out, len(rows), len(rows[0]["x"]) if rows else 0))


if __name__ == "__main__":
    main()
