"""Build a submission that PLAYS THE LEADER'S RECORDED ACTIONS, turn for turn.

TWO tapes and TWO token swaps. Nothing else. No planner, no schedule, no routing.

    TAPE 1  three-quadrant   91919278   the base, played by default
    TAPE 2  four-quadrant    91907974   played from d9 h0 when YARN_STORE unlocked by d6

    swap A  COW -> SHEEP          from the turn YARN_STORE unlocks, on the three-quadrant tape
    swap B  MELON -> STRAWBERRY   from d3 h0, when the opponent holds >= 9 MELON tiles

## Why a literal replay works at all

The board is identical in every game. `_initial_tile(x, y, board_size)` returns
`None if quadrant == "NW" else "LOCKED"` -- a pure function of coordinates -- so tiles, distances
and the shed sit where the tape expects them. Only two things are drawn from `random.Random`: the
weed spawn and the shop unlock order. Movement is EXPLICIT in the action stream (`WEST`, `NORTH`,
`EAST`, `SOUTH` are ops), so the tour is recorded rather than re-derived.

That is what makes a token swap safe: rewriting the ITEM an action names leaves the walk, the hour
and the unit exactly where they were. Nothing has to be re-planned.

What a foreign seed DOES change: a shop that has not unlocked refuses its BUY_SEED, and a purchase
is refused when the bank is short, because the market is contested and our fills differ from the
recording's. The tape cannot react to either -- it plays handicapped.

## Why swap B replaces a third tape

An earlier build carried a third tape, 91891131, the leader's own strawberry-heavy game, and
switched to it at d3. That changes 27 days of actions to answer a question about 8 tiles.

It is also unnecessary, and the tape says so. The three-quadrant tape plants melon on exactly three
days -- `d0: 12, d6: 2, d7: 6` -- and buys its seed on `d0: 12, d5: 3, d6: 5`. So rewriting every
melon from d3 onward leaves MELON 12 and adds 8 STRAWBERRY, which is 91891131's allocation
(MELON 12 / STRAWBERRY 42) exactly. The swap reproduces the tape it replaces.

**The known risk, stated rather than hidden.** MELON is `ongoing: False` -- one harvest at day
10-12, up to 6 units -- and STRAWBERRY is `ongoing: True`, 4 units every 2 days from day 10. The
first harvest day is 10 for both, so the tape's first harvest lands correctly either way. After
that the base tape treats those 8 tiles as spent melon and may dig one that is still producing.
Eight tiles, and worth measuring rather than assuming.

## Why swap A needs its own trigger

COW and SHEEP share the PASTURE structure (`ANIMALS` in the reference), so exchanging one for the
other needs no different building and no different tile.

Its trigger is YARN_STORE unlocking AT ANY POINT, not the d6 test that arms the quadrant branch. Had
it used the d6 test it could only ever act for 49 turns: the same signal arms TAPE 2, which takes
over at d9 h0 carrying its own herd (COW 6 / SHEEP 12 against the base's COW 10 / SHEEP 4).

`PICKUP` and `PLACE` are rewritten alongside `BUY_ANIMAL`, because a purchase changed without its
placement puts a sheep in the shed and leaves the pen empty.

    python -u scripts/build_tape_submission.py --out submission/main_tape2.py
"""
import argparse
import base64
import collections
import gzip
import json
import pathlib
import sys
import time

REPO = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

TEAM = "カワシギ"

#: TWO tapes. 91919278 is the base rather than 92498144 because it measured better as a constant
#: against the same opponent over the same 192 games: 62.5% against 52.6%, a gap wider than the
#: 7.2% noise floor (`docs/decision_points_2026-08-16.md`).
TAPES = {
    "BASE": "data/seed_scripts/downloads_2026-08-13/91919278.json",
    "Q4": "data/seed_scripts/downloads_2026-08-13/91907974.json",
}

#: Written with `@@NAME@@` placeholders and substituted by `str.replace`, NOT by `str.format`.
#: The template is Python source full of braces; a previous version used `.format()` and every
#: literal `{` had to be doubled, which broke the build the moment a dict was added to it.
TEMPLATE = '''"""Kaggriculture submission: the leader's recorded actions. Two tapes, two swaps.

GENERATED by `scripts/build_tape_submission.py`. Do not edit by hand -- rebuild it.

    TAPE 1  three-quadrant  @@BASE_ID@@   the base, played by default
    TAPE 2  four-quadrant   @@Q4_ID@@   from d9 h0 when YARN_STORE unlocked by d6

    swap A  COW -> SHEEP         from the turn YARN_STORE unlocks
    swap B  MELON -> STRAWBERRY  from d3 h0 when the opponent holds >= @@MELON@@ MELON tiles

Both swaps rewrite only the ITEM an action names. Movement is explicit in this tape, so the tour,
the hour and the unit are untouched. COW and SHEEP share the PASTURE structure, so no different
building is needed; `PICKUP` and `PLACE` are rewritten with `BUY_ANIMAL` so a bought animal still
has somewhere to stand.
"""
import base64
import gzip
import json

#: tape -> [action per turn], gzip + base64. Actions only; observations are not needed.
TAPES_B64 = (
@@BLOB@@
)

MELON_TILES_THAT_MEAN_HE_IS_MELON_HEAVY = @@MELON@@
FORK_TURN = @@FORK@@          # d3 h0
DECIDE_TURN = @@DECIDE@@      # d6 h23, the last turn before the split day can act
SPLIT_TURN = @@SPLIT@@        # d9 h0
TRIGGER_SHOP = "YARN_STORE"

HERD_SWAP = {"COW": "SHEEP"}
CROP_SWAP = {"MELON": "STRAWBERRY"}

_TAPES = None
_STATE = {}
IDLE = {"farmer": ["PASS"], "hands": [], "market": []}


def _tapes():
    global _TAPES
    if _TAPES is None:
        _TAPES = json.loads(gzip.decompress(base64.b64decode(TAPES_B64)))
    return _TAPES


def _melon_tiles(farm):
    n = 0
    for row in farm.get("tiles") or []:
        for t in row:
            if isinstance(t, dict) and t.get("crop") == "MELON":
                n += 1
    return n


def _swap(action, pairs):
    """Rewrite the ITEM an action names. The op, the unit and the turn are left alone.

    PLANT and BUY_SEED carry the crop; BUY_ANIMAL, PICKUP and PLACE carry the animal. Rewriting a
    purchase without its placement would put the new animal in the shed and leave the pen empty,
    so they move together.
    """
    out = {"farmer": list(action.get("farmer") or ["PASS"]),
           "hands": [list(h) for h in (action.get("hands") or [])],
           "market": [list(o) for o in (action.get("market") or [])]}
    for op in [out["farmer"]] + out["hands"]:
        if len(op) > 1 and op[0] in ("PLANT", "PICKUP", "PLACE") and op[1] in pairs:
            op[1] = pairs[op[1]]
    for order in out["market"]:
        if len(order) > 1 and order[0] in ("BUY_SEED", "BUY_ANIMAL") and order[1] in pairs:
            order[1] = pairs[order[1]]
    return out


def _unit_ops(action):
    return [list(action.get("farmer") or ["PASS"])] + [list(h) for h in (action.get("hands") or [])]


def _tile_at(tiles, pos):
    if not pos:
        return None
    x, y = pos[0], pos[1]
    if 0 <= y < len(tiles) and 0 <= x < len(tiles[y]):
        return tiles[y][x]
    return None


def _has_slack_left_today(tape, unit, idx):
    """Does this unit have a PASS later in the SAME day to absorb an inserted turn?

    This is the constraint that makes an insert free. Sliding a unit's op stream by one turn costs
    nothing if a later turn that day was going to be idle -- the PASS is simply skipped and the
    stream resynchronises. With no PASS left, the insert would push the day's last op off the end,
    and a weed is cheaper than losing real work.
    """
    day_end = (idx // 24 + 1) * 24
    for j in range(idx + 1, min(day_end, len(tape))):
        ops = _unit_ops(tape[j])
        if unit < len(ops) and ops[unit] and ops[unit][0] == "PASS":
            return True
    return False


#: Ops that CANNOT run on a weeded tile, so a weed there must be dug whatever it costs -- the tape's
#: op would fail silently and the seed be wasted anyway (`_apply_unit_action`, the PLANT branch
#: returns early unless the tile is empty).
BLOCKED_BY_A_WEED = ("PLANT", "BUILD_PASTURE", "BUILD_COOP")


def agent(obs, config=None):
    """Entry point. MUST be the last callable in this file.

    `kaggle_environments.get_last_callable` execs the module and takes the last callable in the
    namespace; it does not look for the name `agent`.

    Each unit carries its own offset into the tape. An inserted DIG slides only that unit's op
    stream, and the slide is absorbed by the next PASS that unit was going to make. The offset is
    cleared at every dawn, so a day can never inherit a shift from the day before.

    **The market stream is never shifted.** It is read from the unshifted turn, so an inserted dig
    can never delay a HIRE, push a SELL past its price window, or move a BUY_LAND to a turn where
    the bank is short.
    """
    me = int(obs.get("player", 0) or 0)
    day = int(obs.get("day", 0) or 0)
    hour = int(obs.get("hour", 0) or 0)
    t = day * 24 + hour

    if t == 0 or me not in _STATE:
        _STATE[me] = {"straw": False, "q4": False, "wool": False, "off": {}}
    st = _STATE[me]
    if hour == 0:
        st["off"] = {}

    farms = obs.get("farms") or []
    shops = list((obs.get("town") or {}).get("unlocked_shops") or [])
    if t == FORK_TURN and len(farms) > 1:
        st["straw"] = _melon_tiles(farms[1 - me]) >= MELON_TILES_THAT_MEAN_HE_IS_MELON_HEAVY
    if TRIGGER_SHOP in shops:
        st["wool"] = True
    if t == DECIDE_TURN:
        st["q4"] = TRIGGER_SHOP in shops

    on_q4 = st["q4"] and t >= SPLIT_TURN
    tape = _tapes()["Q4" if on_q4 else "BASE"]
    if t >= len(tape):
        return IDLE

    farm = farms[me] if len(farms) > me else {}
    tiles = farm.get("tiles") or []
    positions = [farm.get("farmer")] + list(farm.get("hands") or [])

    # The MARKET always comes from the unshifted turn. Swaps apply on whichever tape is playing.
    market = [list(o) for o in (tape[t].get("market") or [])]
    for order in market:
        if len(order) > 1 and order[0] in ("BUY_SEED", "BUY_ANIMAL"):
            if st["straw"] and t >= FORK_TURN and order[1] in CROP_SWAP:
                order[1] = CROP_SWAP[order[1]]
            if st["wool"] and order[1] in HERD_SWAP:
                order[1] = HERD_SWAP[order[1]]

    out = []
    for i, pos in enumerate(positions):
        off = st["off"].get(i, 0)
        idx = t - off
        if idx < 0 or idx >= len(tape):
            out.append(["PASS"])
            continue
        ops = _unit_ops(tape[idx])
        op = list(ops[i]) if i < len(ops) and ops[i] else ["PASS"]

        # Absorb an earlier insert: a PASS this unit was going to make is simply skipped.
        while off > 0 and op[0] == "PASS" and (t - off + 1) <= t:
            off -= 1
            idx = t - off
            ops = _unit_ops(tape[idx]) if idx < len(tape) else [["PASS"]]
            op = list(ops[i]) if i < len(ops) and ops[i] else ["PASS"]

        if st["straw"] and t >= FORK_TURN and len(op) > 1 and op[0] == "PLANT" and op[1] in CROP_SWAP:
            op[1] = CROP_SWAP[op[1]]
        if st["wool"] and len(op) > 1 and op[0] in ("PICKUP", "PLACE") and op[1] in HERD_SWAP:
            op[1] = HERD_SWAP[op[1]]

        tile = _tile_at(tiles, pos)
        kind = tile.get("kind") if isinstance(tile, dict) else None

        # **Never dig a swapped strawberry.** The base tape treats these tiles as spent MELON --
        # one harvest, then dig and replant. STRAWBERRY is `ongoing: True` and yields every 2 days
        # to the end of the season. Digging them measured 0.0% win rate against 66.7% with the swap
        # off, -$17,297 a game over 24 paired games. The swap is only safe with this guard.
        if (op[0] == "DIG" and st["straw"] and isinstance(tile, dict)
                and tile.get("crop") == CROP_SWAP.get("MELON")):
            op = ["PASS"]

        if kind == "WEED":
            if op[0] in BLOCKED_BY_A_WEED:
                # It needs weeding regardless: the tape's op cannot run on a weeded tile.
                st["off"][i] = off + 1
                op = ["DIG"]
            elif op[0] == "PASS":
                op = ["DIG"]                      # free -- the turn was idle anyway
            elif _has_slack_left_today(tape, i, idx):
                st["off"][i] = off + 1
                op = ["DIG"]
            else:
                st["off"][i] = off                # no slack; leave the weed, keep the work
        elif op[0] == "PASS" and kind == "PLANT" and not tile.get("watered_today"):
            op = ["WATER"]                        # free, and no argument -- acts where it stands
        else:
            st["off"][i] = off
        out.append(op)

    return {"farmer": out[0] if out else ["PASS"], "hands": out[1:], "market": market}
'''


def tape_actions(path):
    """The named team's own actions, one per turn, from the seat he held in the recording."""
    d = json.loads((REPO / path).read_text())
    seat = d["info"]["TeamNames"].index(TEAM)
    out = []
    for step in d["steps"][1:]:
        a = (step[seat] or {}).get("action") or {}
        out.append({"farmer": a.get("farmer") or ["PASS"],
                    "hands": list(a.get("hands") or []),
                    "market": list(a.get("market") or [])})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="submission/main_tape2.py")
    ap.add_argument("--seed", type=int, default=11)
    ap.add_argument("--melon-tiles", type=int, default=9)
    #: Build-time only, producing a DISTINCT file -- the control arm for the
    #: idle-turn rule, not a runtime dial in the shipped artifact.
    ap.add_argument("--no-idle-turn", action="store_true")
    a = ap.parse_args()

    acts = {k: tape_actions(v) for k, v in TAPES.items()}
    for k, v in acts.items():
        herd, crop = collections.Counter(), collections.Counter()
        for turn in v:
            for o in turn["market"]:
                if o[0] == "BUY_ANIMAL":
                    herd[o[1]] += o[2]
            for op in [turn["farmer"]] + turn["hands"]:
                if op and op[0] == "PLANT":
                    crop[op[1]] += 1
        print(f"{k:<5}{TAPES[k].split('/')[-1]:<16} turns {len(v)}  buys {dict(herd)}  "
              f"plants {dict(crop)}")

    fork, decide, split = 3 * 24, 6 * 24 + 23, 9 * 24
    # what swap B does to the base, counted rather than asserted
    mel_before = sum(1 for turn in acts["BASE"] for op in [turn["farmer"]] + turn["hands"]
                     if op and op[0] == "PLANT" and op[1] == "MELON")
    mel_after3 = sum(1 for i, turn in enumerate(acts["BASE"]) if i >= fork
                     for op in [turn["farmer"]] + turn["hands"]
                     if op and op[0] == "PLANT" and op[1] == "MELON")
    print(f"\nswap B rewrites {mel_after3} of the base's {mel_before} melon plants "
          f"-> MELON {mel_before - mel_after3} / STRAWBERRY +{mel_after3}")
    print("   91891131, the leader's own strawberry-heavy game, plants MELON 12 / STRAWBERRY 42.")

    raw = json.dumps(acts, separators=(",", ":")).encode()
    blob = base64.b64encode(gzip.compress(raw, 9)).decode()
    lines = "\n".join(f'    "{blob[i:i + 92]}"' for i in range(0, len(blob), 92))
    src = (TEMPLATE.replace("@@BLOB@@", lines)
                   .replace("@@MELON@@", str(a.melon_tiles))
                   .replace("@@FORK@@", str(fork))
                   .replace("@@DECIDE@@", str(decide))
                   .replace("@@SPLIT@@", str(split))
                   .replace("@@BASE_ID@@", pathlib.Path(TAPES["BASE"]).stem)
                   .replace("@@Q4_ID@@", pathlib.Path(TAPES["Q4"]).stem))
    if a.no_idle_turn:
        src = src.replace("return _use_the_idle_turn(action, farms[me]) if len(farms) > me "
                          "else action", "return action")
    assert "@@" not in src, "a placeholder was left unsubstituted"
    out = REPO / a.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(src)
    print(f"\nwrote {a.out} ({len(src.splitlines())} lines, {len(src) / 1024:.0f} KB)")

    ns = {}
    exec(compile(src, str(out), "exec"), ns)
    assert [v for v in ns.values() if callable(v)][-1] is ns["agent"], (
        "the last callable is not agent(); kaggle_environments would call the wrong one")
    print("entry point OK: the last callable is agent()")

    from kaggle_environments import make
    env = make("kaggriculture", configuration={"seed": a.seed, "weedSpawnChance": 0.005}, debug=True)
    env.reset(2)
    worst = total = 0.0
    for t in range(719):
        s = time.perf_counter()
        act = ns["agent"](env.state[0].observation, None)
        dt = time.perf_counter() - s
        worst, total = max(worst, dt), total + dt
        env.step([act, {"farmer": ["PASS"], "hands": [], "market": []}])
        if env.done:
            break
    fin = env.steps[-1]
    print(f"vs an idle opponent, seed {a.seed}: ${fin[0]['reward']:,.0f} vs ${fin[1]['reward']:,.0f}"
          f"   (a smoke test -- idle contests nothing, it is NOT a result)")
    print(f"turn time over {t + 1} turns: worst {worst * 1000:.0f} ms, mean {total / (t + 1) * 1000:.1f} ms")
    assert fin[0]["reward"] > 3000, "banked no more than the start -- the tape is not playing"
    print("built and verified. NOT submitted.")


if __name__ == "__main__":
    main()
