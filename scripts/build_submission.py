"""Build `submission/main.py` from the agent source, verbatim.

The agent is deliberately dependency-free so the submitted file can be a byte-for-byte copy of
the file the arena tests. The only addition is a comment header -- nothing that could change
how the module parses.

An earlier hand-rolled version of this spliced a new docstring over the first line, which left
the original docstring's body as loose module-level text. The module failed to import, the
environment fell back to no-ops, and the agent banked exactly its $3000 starting money. Hence
this script, and hence `verify` below.

Run: .venv/bin/python scripts/build_submission.py
"""

import pathlib
import sys

SOURCE = pathlib.Path("kagg/agents/heuristic.py")
TARGET = pathlib.Path("submission/main.py")
HEADER = (
    "# Generated by scripts/build_submission.py from kagg/agents/heuristic.py -- do not edit.\n"
    "# Edit the source agent and rebuild, so the submitted file cannot drift from the tested one.\n"
)


def build():
    TARGET.parent.mkdir(exist_ok=True)
    TARGET.write_text(HEADER + SOURCE.read_text())
    return TARGET


def verify(seeds=range(600, 604)):
    """Play the built file against `starter` and confirm it actually farms.

    A module that fails to import scores exactly the $3000 starting money, so anything at or
    below the start is treated as a build failure rather than a weak agent.
    """
    from kagg.arena import run_arena

    report = run_arena(str(TARGET), "starter", seeds=list(seeds), workers=4)
    ok = report.mean_money[0] > 3000.0 and report.win_rate == 1.0
    return ok, report


if __name__ == "__main__":
    path = build()
    print(f"wrote {path} ({len(path.read_text().splitlines())} lines)")
    ok, report = verify()
    print(report)
    if not ok:
        print("BUILD FAILED: submission does not beat starter from every seat", file=sys.stderr)
        sys.exit(1)
    print("submission verified")
