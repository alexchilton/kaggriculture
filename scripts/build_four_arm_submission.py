"""Build the FOUR-ARM tape submission: one player's own branches, at his own three latch points.

    latch  turn           test                          arm         tape
      1     88  d3h16     YARN_STORE unlocked by d3     yarn3       98859585
      2    153  d6h9      YARN_STORE unlocked by d6     yarn6       98889289
      3    242  d10h2     opponent money > 650          rich        98852727
      -    default                                      open        98884730

Every arm is UjjwalPardeshi, so the arms are prefix-compatible BY CONSTRUCTION rather than by luck:
they are one player's branches of one script. The shipped three-arm build stitches three DIFFERENT
players (WeAreFarmers, nao.kwmr, UjjwalPardeshi) at a single latch.

Measured 2026-08-26 on 110 draws, each draw's own recorded opponent, seed 123641874, scored on WINS
because the ladder is Elo:

    FOUR SPLITS       49/110   44.5%   mean margin   -121
    shipped 3-arm     41/110   37.3%   mean margin -1,640
    differs on 38 draws: 8 losses turned into wins, 0 wins turned into losses

**That number is IN-SAMPLE.** The 650 threshold was read off nine of his games in that corpus and
the arm tapes' own draws sit among the 110. Held-out draws are what test it.

## No planner, no schedule, no routes, no handover

Three handover sweeps (`handover_all_draws`, `handover_fine`, `handover_class`, 18-27 draws each)
put the planner BELOW the full tape at every handover day tested; the best was d22 at -$137. The
planner builder's own note agrees: *"d28 is the best handover on EVERY draw and the tape with no
planner beats it on every draw, by $995 to $2,648."* So this bundle is tape only.

## No token swaps

`build_tape_submission.py` carries `HERD_SWAP = {"COW": "SHEEP"}` and
`CROP_SWAP = {"MELON": "STRAWBERRY"}`. Both are dropped here.

- **HERD_SWAP** -- removed on Alex's instruction. A full-season COW->SHEEP rewrite measured
  **-$25,573, 0 of 27 draws, 3 of 81 head-to-head** (`data/logs/species_swap_arm_v2.csv`). The loss
  is the book, not the cadence: the same 192 units of wool fetch $2,356 on a draw with no yarn store
  and $25,326 on one with two.
- **CROP_SWAP** -- also dropped, and this one was not asked for, so it is called out here. It is
  keyed to the kawashigi tape generation (`919xxxxx`), was never measured against these arms, and
  the arms already carry their own crop mix. Re-adding it needs its own measurement.

## Verbatim replay, deliberately

`build_tape_submission.py` also inserts DIG on a weeded tile and WATER on an idle one. Those are NOT
carried here, because the 49/110 was measured on a VERBATIM replay -- the harness played the tape
turn for turn with weeds live at the recorded `weedSpawnChance`. Adding either rule would make the
artifact something other than the thing that was measured. They are worth measuring separately.
"""

import argparse
import base64
import collections
import gzip
import json
import pathlib
import sys
import time

REPO = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

TEAM = "UjjwalPardeshi"
SRC = "data/seed_scripts/daily_2026-08-26"

#: arm -> (episode, what selects it). `open` is the default and is never selected, only fallen to.
ARMS = {
    "yarn3": "98859585",
    "yarn6": "98889289",
    "rich": "98852727",
    "open": "98884730",
}

LATCH_1 = 3 * 24 + 16     # 88   d3h16  -- yarn store in the d3 draw
LATCH_2 = 6 * 24 + 9      # 153  d6h9   -- yarn store by the d6 draw
LATCH_3 = 10 * 24 + 2     # 242  d10h2  -- the opponent's bank

#: Midpoint of the gap in his nine cow games: 487..507 plant eight strawberries on d10, 795..2192
#: plant eleven. `GPTatoes` appears in BOTH groups, so it is their CASH and not their identity.
OPP_MONEY_THRESHOLD = 650

#: Each arm must be byte-identical to `open` for every turn BEFORE the latch that can select it,
#: or the bundle replays actions the earlier turns never took. Asserted at build time.
PREFIX_GATE = {"yarn3": LATCH_1, "yarn6": LATCH_2, "rich": LATCH_3}

TEMPLATE = '''"""Kaggriculture submission: four tapes, one player, three latch points.

GENERATED by `scripts/build_four_arm_submission.py` -- do not edit by hand, rebuild it.

    latch  turn           test                            arm     tape
      1     @@L1@@  d3h16     YARN_STORE unlocked by d3       yarn3   @@YARN3@@
      2    @@L2@@  d6h9      YARN_STORE unlocked by d6       yarn6   @@YARN6@@
      3    @@L3@@  d10h2     opponent money > @@THRESH@@             rich    @@RICH@@
      -    default                                          open    @@OPEN@@

Every arm is one player's own branch, so all four are byte-identical before the latch that can
select them -- asserted at build time, not assumed.

No planner, no schedule, no routes, no token swaps, no weed handling. The tape is replayed verbatim.
"""
import base64
import gzip
import json

#: arm -> [action per turn], gzip + base64. Actions only; observations are not needed.
TAPES_B64 = (
@@BLOB@@
)

LATCH_1 = @@L1@@
LATCH_2 = @@L2@@
LATCH_3 = @@L3@@
OPP_MONEY_THRESHOLD = @@THRESH@@
TRIGGER_SHOP = "YARN_STORE"
DEFAULT_ARM = "open"

_TAPES = None
_STATE = {}
IDLE = {"farmer": ["PASS"], "hands": [], "market": []}


def _tapes():
    global _TAPES
    if _TAPES is None:
        _TAPES = json.loads(gzip.decompress(base64.b64decode(TAPES_B64)))
    return _TAPES


def agent(obs, config=None):
    """Entry point. MUST be the last callable in this file.

    `kaggle_environments.get_last_callable` execs the module and takes the last callable in the
    namespace; it does not look for the name `agent`.

    **The arm only ever moves away from `open`.** Latch 2 and latch 3 are guarded on the arm still
    being `open`, so an early yarn store is never overwritten by a later signal. Once set, an arm is
    kept for the rest of the season -- there is no un-latching, because the tapes have already
    diverged by then and switching back would replay actions the board never took.
    """
    me = int(obs.get("player", 0) or 0)
    day = int(obs.get("day", 0) or 0)
    hour = int(obs.get("hour", 0) or 0)
    t = day * 24 + hour

    if t == 0 or me not in _STATE:
        _STATE[me] = {"arm": DEFAULT_ARM}
    st = _STATE[me]

    shops = list((obs.get("town") or {}).get("unlocked_shops") or [])
    farms = obs.get("farms") or []

    if t == LATCH_1:
        if TRIGGER_SHOP in shops:
            st["arm"] = "yarn3"
    elif t == LATCH_2:
        if st["arm"] == DEFAULT_ARM and TRIGGER_SHOP in shops:
            st["arm"] = "yarn6"
    elif t == LATCH_3:
        # `farms[1 - me]`, NOT `farms[1]`. The measurement harness always sat at seat 0 and could
        # hard-code the index; the ladder seats us either side.
        if st["arm"] == DEFAULT_ARM and len(farms) > 1:
            opp = farms[1 - me] or {}
            if float(opp.get("money", 0) or 0) > OPP_MONEY_THRESHOLD:
                st["arm"] = "rich"

    tape = _tapes()[st["arm"]]
    if t >= len(tape):
        return IDLE
    a = tape[t]
    return {"farmer": list(a.get("farmer") or ["PASS"]),
            "hands": [list(h) for h in (a.get("hands") or [])],
            "market": [list(o) for o in (a.get("market") or [])]}
'''


def tape_actions(episode):
    """The named team's own actions, one per turn, from the seat he held in that recording."""
    path = REPO / SRC / f"{episode}.json"
    d = json.loads(path.read_text())
    names = d["info"]["TeamNames"]
    if TEAM not in names:
        raise SystemExit(f"{episode}: {TEAM} is not in {names}")
    seat = names.index(TEAM)
    out = []
    for step in d["steps"][1:]:
        a = (step[seat] or {}).get("action") or {}
        out.append({"farmer": a.get("farmer") or ["PASS"],
                    "hands": list(a.get("hands") or []),
                    "market": list(a.get("market") or [])})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="submission/main_four_arm.py")
    ap.add_argument("--seed", type=int, default=11)
    a = ap.parse_args()

    acts = {arm: tape_actions(ep) for arm, ep in ARMS.items()}
    print(f"{'arm':<7}{'episode':<11}{'turns':>7}   herd                 plants")
    for arm, v in acts.items():
        herd, crop = collections.Counter(), collections.Counter()
        for turn in v:
            for o in turn["market"]:
                if o and o[0] == "BUY_ANIMAL":
                    herd[o[1]] += int(o[2])
            for op in [turn["farmer"]] + turn["hands"]:
                if op and op[0] == "PLANT":
                    crop[op[1]] += 1
        print(f"{arm:<7}{ARMS[arm]:<11}{len(v):>7}   {str(dict(herd)):<21}{dict(crop)}")

    # THE GATE. Each arm must match `open` on every turn before the latch that can select it.
    base = acts["open"]
    print(f"\nprefix gate -- each arm against `open`:")
    for arm, cut in PREFIX_GATE.items():
        v = acts[arm]
        n = min(cut, len(v), len(base))
        bad = [t for t in range(n)
               if json.dumps(v[t], sort_keys=True) != json.dumps(base[t], sort_keys=True)]
        agree = next((t for t in range(min(len(v), len(base)))
                      if json.dumps(v[t], sort_keys=True) != json.dumps(base[t], sort_keys=True)),
                     min(len(v), len(base)))
        status = "OK" if not bad else f"DIFFERS at turn {bad[0]}"
        print(f"  {arm:<7}identical required through {cut:>4}   actually identical through "
              f"{agree:>4}   {status}")
        if bad:
            raise SystemExit(
                f"arm {arm!r} differs from `open` at turn {bad[0]}, before its latch at {cut}. "
                f"The bundle would replay actions the earlier turns never took.")

    raw = json.dumps(acts, separators=(",", ":")).encode()
    blob = base64.b64encode(gzip.compress(raw, 9)).decode()
    lines = "\n".join(f'    "{blob[i:i + 92]}"' for i in range(0, len(blob), 92))
    src = (TEMPLATE.replace("@@BLOB@@", lines)
                   .replace("@@L1@@", str(LATCH_1))
                   .replace("@@L2@@", str(LATCH_2))
                   .replace("@@L3@@", str(LATCH_3))
                   .replace("@@THRESH@@", str(OPP_MONEY_THRESHOLD))
                   .replace("@@YARN3@@", ARMS["yarn3"])
                   .replace("@@YARN6@@", ARMS["yarn6"])
                   .replace("@@RICH@@", ARMS["rich"])
                   .replace("@@OPEN@@", ARMS["open"]))
    assert "@@" not in src, "a placeholder was left unsubstituted"
    out = REPO / a.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(src)
    print(f"\nwrote {a.out} ({len(src.splitlines())} lines, {len(src) / 1024:.0f} KB)")

    ns = {}
    exec(compile(src, str(out), "exec"), ns)
    assert [v for v in ns.values() if callable(v)][-1] is ns["agent"], (
        "the last callable is not agent(); kaggle_environments would call the wrong one")
    print("entry point OK: the last callable is agent()")

    from kaggle_environments import make
    env = make("kaggriculture", configuration={"seed": a.seed, "weedSpawnChance": 0.005}, debug=True)
    env.reset(2)
    worst = total = 0.0
    for t in range(719):
        s = time.perf_counter()
        act = ns["agent"](env.state[0].observation, None)
        dt = time.perf_counter() - s
        worst, total = max(worst, dt), total + dt
        env.step([act, {"farmer": ["PASS"], "hands": [], "market": []}])
        if env.done:
            break
    fin = env.steps[-1]
    print(f"vs an idle opponent, seed {a.seed}: ${fin[0]['reward']:,.0f} vs ${fin[1]['reward']:,.0f}"
          f"   (a SMOKE TEST -- idle contests nothing, it is NOT a result)")
    print(f"turn time over {t + 1} turns: worst {worst * 1000:.0f} ms, "
          f"mean {total / (t + 1) * 1000:.1f} ms")
    assert fin[0]["reward"] > 3000, "banked no more than the start -- the tape is not playing"

    # Which arm did the smoke test end on, and did every latch fire at all?
    print(f"smoke-test arm: {ns['_STATE'].get(0, {}).get('arm')}")
    print("built and verified. NOT submitted.")


if __name__ == "__main__":
    main()
