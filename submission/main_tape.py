MELON_TILES_THAT_MEAN_HE_IS_MELON_HEAVY = 9
FORK_TURN = 72          # d3 h0
DECIDE_TURN = 167      # d6 h23, the last turn before the split day can act
SPLIT_TURN = 216        # d9 h0
TRIGGER_SHOP = "YARN_STORE"

_TAPES = None
_STATE = {}
IDLE = {"farmer": ["PASS"], "hands": [], "market": []}


def _tapes():
    global _TAPES
    if _TAPES is None:
        _TAPES = json.loads(gzip.decompress(base64.b64decode(TAPES_B64)))
    return _TAPES


def _melon_tiles(farm):
    n = 0
    for row in farm.get("tiles") or []:
        for t in row:
            if isinstance(t, dict) and t.get("crop") == "MELON":
                n += 1
    return n


def _swap_herd(action):
    """COW -> SHEEP everywhere this turn names an animal. Same pasture, same tile, same turn."""
    out = {"farmer": list(action.get("farmer") or ["PASS"]),
           "hands": [list(h) for h in (action.get("hands") or [])],
           "market": [list(o) for o in (action.get("market") or [])]}
    for op in [out["farmer"]] + out["hands"]:
        if len(op) > 1 and op[0] in ("PICKUP", "PLACE") and op[1] == "COW":
            op[1] = "SHEEP"
    for order in out["market"]:
        if len(order) > 1 and order[0] == "BUY_ANIMAL" and order[1] == "COW":
            order[1] = "SHEEP"
    return out


def agent(obs, config=None):
    """Entry point. MUST be the last callable in this file.

    `kaggle_environments.get_last_callable` execs the module and takes the last callable in the
    namespace -- it does not look for the name `agent`. A helper defined below this one becomes the
    entry point and is called with the observation as its first argument.
    """
    me = int(obs.get("player", 0) or 0)
    day = int(obs.get("day", 0) or 0)
    hour = int(obs.get("hour", 0) or 0)
    t = day * 24 + hour

    if t == 0 or me not in _STATE:
        _STATE[me] = {"straw": False, "q4": False}
    st = _STATE[me]

    farms = obs.get("farms") or []
    if t == FORK_TURN and len(farms) > 1:
        st["straw"] = _melon_tiles(farms[1 - me]) >= MELON_TILES_THAT_MEAN_HE_IS_MELON_HEAVY
    if t == DECIDE_TURN:
        st["q4"] = TRIGGER_SHOP in list((obs.get("town") or {}).get("unlocked_shops") or [])

    tapes = _tapes()
    if st["q4"] and t >= SPLIT_TURN:
        tape = tapes["Q4"]
    elif st["straw"] and t >= FORK_TURN:
        tape = tapes["B3"]
    else:
        tape = tapes["A3"]

    action = tape[t] if t < len(tape) else IDLE
    # The herd only needs rewriting on the base tape between the signal and the handover: Q4
    # already carries COW 6 / SHEEP 12, and before d6 h23 there is no signal to act on.
    if st["q4"] and DECIDE_TURN <= t < SPLIT_TURN:
        action = _swap_herd(action)
    return action
