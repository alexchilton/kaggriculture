_STATE = {}
IDLE = {"farmer": ["PASS"], "hands": [], "market": []}


def _tapes():
    global _TAPES
    if _TAPES is None:
        _TAPES = json.loads(gzip.decompress(base64.b64decode(TAPES_B64)))
    return _TAPES


def _melon_tiles(farm):
    n = 0
    for row in farm.get("tiles") or []:
        for t in row:
            if isinstance(t, dict) and t.get("crop") == "MELON":
                n += 1
    return n


def _swap(action, pairs):
    """Rewrite the ITEM an action names. The op, the unit and the turn are left alone.

    PLANT and BUY_SEED carry the crop; BUY_ANIMAL, PICKUP and PLACE carry the animal. Rewriting a
    purchase without its placement would put the new animal in the shed and leave the pen empty,
    so they move together.
    """
    out = {"farmer": list(action.get("farmer") or ["PASS"]),
           "hands": [list(h) for h in (action.get("hands") or [])],
           "market": [list(o) for o in (action.get("market") or [])]}
    for op in [out["farmer"]] + out["hands"]:
        if len(op) > 1 and op[0] in ("PLANT", "PICKUP", "PLACE") and op[1] in pairs:
            op[1] = pairs[op[1]]
    for order in out["market"]:
        if len(order) > 1 and order[0] in ("BUY_SEED", "BUY_ANIMAL") and order[1] in pairs:
            order[1] = pairs[order[1]]
    return out


def _use_the_idle_turn(action, farm):
    """Turn a PASS into free work on the tile the unit is ALREADY standing on.

    A PASS costs nothing and moves nobody, and both ops below take no argument and act on the
    current tile, so this cannot desynchronise the tape: no unit moves, no money changes hands, and
    no later turn expects anything different.

        WATER   free. Requires kind == "PLANT" and not watered_today (`kaggriculture.py:431`).
                Inside a one-shot crop's window it also adds a yield unit.
        DIG     free, but it REMOVES PLANTS as well as weeds (`:484`). Guarded on kind == "WEED";
                unguarded it would destroy standing crops, which is the opposite of the point.

    The base tape passes on 672 turns. Every one of them is a turn the recording spent doing
    nothing while, on a foreign seed, a weed may have appeared under that unit's feet.
    """
    tiles = farm.get("tiles") or []
    units = [farm.get("farmer")] + list(farm.get("hands") or [])
    ops = [action.get("farmer") or ["PASS"]] + [list(h) for h in (action.get("hands") or [])]
    out, changed = [], False
    for i, op in enumerate(ops):
        if op and op[0] == "PASS" and i < len(units) and units[i]:
            x, y = units[i][0], units[i][1]
            tile = tiles[y][x] if 0 <= y < len(tiles) and 0 <= x < len(tiles[y]) else None
            if isinstance(tile, dict):
                if tile.get("kind") == "WEED":
                    op, changed = ["DIG"], True
                elif tile.get("kind") == "PLANT" and not tile.get("watered_today"):
                    op, changed = ["WATER"], True
        out.append(op)
    if not changed:
        return action
    return {"farmer": out[0], "hands": out[1:], "market": list(action.get("market") or [])}


def agent(obs, config=None):
    """Entry point. MUST be the last callable in this file.

    `kaggle_environments.get_last_callable` execs the module and takes the last callable in the
    namespace; it does not look for the name `agent`. A helper defined below this one becomes the
    entry point and is handed the observation as its first argument.
    """
    me = int(obs.get("player", 0) or 0)
    day = int(obs.get("day", 0) or 0)
    hour = int(obs.get("hour", 0) or 0)
    t = day * 24 + hour

    if t == 0 or me not in _STATE:
        _STATE[me] = {"straw": False, "q4": False, "wool": False}
    st = _STATE[me]

    farms = obs.get("farms") or []
    shops = list((obs.get("town") or {}).get("unlocked_shops") or [])
    if t == FORK_TURN and len(farms) > 1:
        st["straw"] = _melon_tiles(farms[1 - me]) >= MELON_TILES_THAT_MEAN_HE_IS_MELON_HEAVY
    if TRIGGER_SHOP in shops:
        st["wool"] = True
    if t == DECIDE_TURN:
        st["q4"] = TRIGGER_SHOP in shops

    on_q4 = st["q4"] and t >= SPLIT_TURN
    tape = _tapes()["Q4" if on_q4 else "BASE"]
    action = tape[t] if t < len(tape) else IDLE

    # Swap B applies to the BASE tape only. Applying it to tape 2 as well cost us the fourth
    # quadrant: STRAWBERRY seed is $100 against MELON's $80, and $160 of extra spend left the bank
    # at $148 when the d12 parcel was offered. `_do_buy_land` refuses silently on a short bank, so
    # the arm ended on 75 tiles instead of 100 -- the whole point of arming it. Measured on seeds
    # 3 and 17 against the frozen opponent.
    if st["straw"] and t >= FORK_TURN and not on_q4:
        action = _swap(action, CROP_SWAP)
    # Swap A only on the base. Tape 2 already carries COW 6 / SHEEP 12 of its own.
    if st["wool"] and not on_q4:
        action = _swap(action, HERD_SWAP)
    return _use_the_idle_turn(action, farms[me]) if len(farms) > me else action
